// La regla de serie solo actúa sobre comandos de shell.
func TestDestructiveShellOnlyForBash(t *testing.T) {
	v := EvaluateRules(RuleEventPrompt, RuleInput{Prompt: "rm -rf /"}, BuiltinRules())
	if v.Action != RuleAllow {
		t.Fatalf("un prompt no es un comando: %+v", v)
	}
}
