package cli

import (
	"fmt"
	"os"
	"regexp"
	"strings"

	"mem/adapters/primary/setup"
	"mem/domain"
)

// retireGlobalBlocks quita los bloques marcados de gomemory de los archivos de
// instrucciones de usuario. Copia cada archivo antes de tocarlo: si la copia
// falla, ese archivo no se modifica. Un archivo sin bloques no se copia, lo que
// hace idempotente la migración. Solo actúa sobre bloques con inicio y fin: sin
// cierre no se sabe dónde termina lo de gomemory y empieza el texto de la
// persona, así que el archivo queda intacto y se informa. Devuelve las rutas
// retiradas.
func retireGlobalBlocks(paths []string, stamp string) ([]string, []error) {
	var retired []string
	var errs []error
	for _, path := range paths {
		// Un enlace de dotfiles se migra en su destino: el rename del reemplazo
		// sustituiría el enlace por un archivo normal.
		real := setup.GlobalConfigPath(path)
		data, err := os.ReadFile(real)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			errs = append(errs, err)
			continue
		}
		content := string(data)
		rest, err := stripMarkedBlocks(content)
		if err != nil {
			errs = append(errs, fmt.Errorf("%s no se modificó: %w", real, err))
			continue
		}
		if rest == content {
			continue
		}
		if err := copyBeforeRetire(real, data, stamp); err != nil {
			errs = append(errs, err)
			continue
		}
		if err := writeRetired(real, rest); err != nil {
			errs = append(errs, err)
			continue
		}
		retired = append(retired, path)
	}
	return retired, errs
}

// stripMarkedBlocks devuelve content sin los bloques completos de gomemory. Un
// encabezado sin marcador es texto de la persona. Falla, sin cambios, ante un
// marcador de inicio o de fin sin su pareja.
func stripMarkedBlocks(content string) (string, error) {
	rest := content
	for _, k := range []struct {
		start *regexp.Regexp
		end   string
	}{
		{domain.UniversalInstructionsVersionPattern, universalInstructionsEndMarker},
		{domain.ProtocolVersionPattern, integrationEndMarker},
	} {
		for {
			loc := k.start.FindStringIndex(rest)
			if loc == nil {
				break
			}
			tail := rest[loc[1]:]
			end := strings.Index(tail, k.end)
			if end == -1 || k.start.MatchString(tail[:end]) {
				return content, fmt.Errorf("bloque de gomemory sin marcador de cierre; revísalo a mano")
			}
			rest = cutBlock(rest, loc[0], loc[1]+end+len(k.end))
		}
		if strings.Contains(rest, k.end) {
			return content, fmt.Errorf("marcador de cierre de gomemory sin inicio; revísalo a mano")
		}
	}
	return rest, nil
}

// cutBlock quita [start, end) con su fin de línea y, si deja dos líneas vacías
// seguidas, una de ellas. El resto del archivo no cambia, CRLF incluido.
func cutBlock(s string, start, end int) string {
	before, after := s[:start], trimEOL(s[end:])
	if before == "" || strings.HasSuffix(before, "\n\n") || strings.HasSuffix(before, "\n\r\n") {
		after = trimEOL(after)
	}
	return before + after
}

func trimEOL(s string) string {
	if strings.HasPrefix(s, "\r\n") {
		return s[2:]
	}
	return strings.TrimPrefix(s, "\n")
}

// writeRetired escribe el resultado o elimina el archivo si no queda nada propio.
func writeRetired(path, rest string) error {
	if trimmed := strings.TrimSpace(rest); trimmed == "" || isAutoGeneratedTitle(trimmed) {
		return os.Remove(path)
	}
	return writeFileAtomic(path, []byte(rest), fileMode(path))
}

// copyBeforeRetire nunca reemplaza una copia previa: O_EXCL hace fallar una
// colisión, y con ello se deja intacto el original.
func copyBeforeRetire(path string, data []byte, stamp string) error {
	backup := path + ".gomemory-backup-" + stamp
	f, err := os.OpenFile(backup, os.O_CREATE|os.O_EXCL|os.O_WRONLY, fileMode(path))
	if err != nil {
		return fmt.Errorf("copiar %s antes de retirar sus bloques: %w", path, err)
	}
	_, err = f.Write(data)
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = os.Remove(backup)
		return fmt.Errorf("copiar %s antes de retirar sus bloques: %w", path, err)
	}
	return nil
}
